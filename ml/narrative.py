"""Case summaries for analysts, written from a ring's own facts and from hand-written meanings of its signals.

Every number, role count and id comes from the scorer's output through a fixed template. The one sentence that says what the
main signal can mean comes from MEANINGS below, written by us, and is cautious ("can", "may") because a signal is evidence,
not proof. Nothing here is generated by a model, and the summary ends with "Verify the accounts before any action; roles are
estimates."

Why not a language model? We tried IBM Granite 4.0 350M (the base model on the platform, run by llama.cpp with zDNN on the
accelerator). Asked for a whole summary it attached numbers to the wrong facts ("Two likely victims" for a ring with one);
restricted to one sentence with no numbers, it still wrote confident nonsense for signals outside its three examples ("A payment
made by a credit card is a payment made by a credit card" for "paid by ach"; "The receiver of a payment is often the same person
who sent it" for "the receiver passes the money on quickly"). A check can reject numbers and accusations but not wrong meaning,
so nothing the model writes reaches a user. The numbers are in docs/ML_RESULTS.md.
"""
import re

CLOSING = "Verify the accounts before any action; roles are estimates."

# (pattern on the feature name without its s_/d_ prefix, meaning). The first match wins. These describe what a signal
# can indicate for pig-butchering-style flows; none of them says an account is guilty.
MEANINGS = [
    (r"^(pt_min|pt_median|fast_out_share|prev_in_gap|next_out_gap|prev_in_ratio|next_out_ratio)$",
     "Money that arrives and is passed on within minutes is typical of accounts used to move funds along rather than to hold or spend them."),
    (r"^(no_prior_in_share)$",
     "Sending money that was never received first can mean the account is being funded from outside what we can see."),
    (r"^(reciprocity)$",
     "Money moving back and forth between the same accounts can be used to make activity look ordinary."),
    (r"^(dup_amount_share|repeat_out|out_cv)$",
     "Repeated amounts or repeated recipients can mean payments are split or scripted rather than made by ordinary customers."),
    (r"^(fan_in_ratio|n_in_cp|fanin_\w+|in_cnt)$",
     "Many different payers feeding a few accounts is the shape of victims paying into collection accounts."),
    (r"^(n_out_cp|fanout_\w+|out_cnt|max_tx_per_hour|velocity)$",
     "Money spread to many accounts, or bursts of payments in a short time, can be used to break up and hide a flow."),
    (r"^(cyc3|ffl|kcore|clustering|comp_size|comp_avg_deg|two_hop_\w+)$",
     "Tightly interlinked accounts can hide where money came from and where it goes."),
    (r"^(pagerank|out_nb_in_cp_mean|in_nb_out_cp_mean)$",
     "An account at the centre of a payment network can be a hub that collects and redistributes money."),
    (r"^(nb_\w+|s1)$",
     "Accounts around it also look risky, which can mean it belongs to a wider network rather than being a one-off."),
    (r"^(cross_ccy|cross_ccy_share)$",
     "Frequent currency changes can make a money trail harder to follow."),
    (r"^(amount_norm|log_amount|out_sum|in_sum|out_max|in_max|out_mean|in_mean|out_in_ratio)$",
     "Payment amounts that are unusual for their currency can be a sign that funds are being moved in bulk."),
    (r"^(span_h|hours_active|self_share|self_transfer)$",
     "How and when the account is used can differ from ordinary customers in ways worth checking."),
    (r"^(ch_\w+|out_share_\w+|in_share_\w+)$",
     "An unusual mix of payment channels can point to money being moved in ways ordinary customers do not."),
]


def meaning_for(feature: str) -> str | None:
    base = feature[2:] if feature[:2] in ("s_", "d_") else feature
    for pattern, text in MEANINGS:
        if re.match(pattern, base):
            return text
    return None


def clean_reason(label: str) -> str:
    """A reason label without its Sender:/Receiver: prefix, lower-case, ready to put in a sentence."""
    text = re.sub(r"^(Sender|Receiver): ", "", label).replace(" (absent)", "")
    return text[0].lower() + text[1:] if text else text


def case_summary(ring: dict, payments: int | None = None) -> str:
    """Three to four sentences for one ring (the dict built by Scorer._describe_ring). `payments` is the true count when
    the ring dict carries only the newest edges."""
    roles: dict[str, int] = {}
    for m in ring["members"]:
        roles[m["role"]] = roles.get(m["role"], 0) + 1
    present = [r for r in ring["top_reasons"] if r.get("contribution", 0) > 0 and "(absent)" not in r["label"]]
    first = (f"Ring {ring['ring_id']} links {ring['accounts']} accounts through {len(ring['edges']) if payments is None else payments} payments and scores "
             f"{ring['risk']} of 100.")
    parts = [first]
    if present:
        parts.append(f"The main signal is: {clean_reason(present[0]['label'])}.")
        meaning = meaning_for(present[0]["feature"])
        if meaning:
            parts.append(meaning)
    shape = [f"{roles[r]} {one if roles[r] == 1 else many}" for r, one, many in (
        ("victim", "likely victim", "likely victims"), ("collector", "collector", "collectors"), ("mule", "mule", "mules"),
        ("cashout", "cash-out", "cash-outs")) if roles.get(r)]
    if shape:
        parts.append("Estimated roles: " + ", ".join(shape[:-1]) + (" and " if len(shape) > 1 else "") + shape[-1] + ".")
    parts.append(CLOSING)
    return " ".join(parts)
